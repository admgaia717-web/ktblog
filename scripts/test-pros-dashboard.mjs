import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require = createRequire(process.env.PROS_QA_PACKAGE || '/tmp/pros-dashboard-qa/package.json');
const {JSDOM} = require('jsdom');
const html = readFileSync('public/pros/dashboard/index.html', 'utf8');
const dom = new JSDOM(html, {url: 'https://ktblog.pages.dev/pros/dashboard/'});
const d = dom.window.document;
assert.equal(d.querySelector('main > section').id, 'deliverables', '成果物がメインの先頭であること');
console.log('PASS 成果物が先頭');
for (const id of ['board','flow','picture','decisions','roadmap','issues','core','rules','next']) {
  const panel = d.getElementById(id).querySelector('details');
  assert.ok(panel && !panel.open, `${id}: 詳細は初期表示では折りたたむ`);
}
assert.ok(!d.querySelector('.hero'), '大きな説明ヒーローを表示しない');
console.log('PASS 情報は段階的に開示');
const js = readFileSync('public/pros/dashboard/dashboard.js', 'utf8');
const live = new JSDOM(html, {url:'https://ktblog.pages.dev/pros/dashboard/#flow',runScripts:'outside-only',pretendToBeVisual:true});
live.window.IntersectionObserver = class { observe() {} };
live.window.scrollTo = () => {};
live.window.eval(js);
await new Promise(resolve => live.window.addEventListener('DOMContentLoaded', resolve));
await new Promise(resolve => setTimeout(resolve,40));
assert.ok(live.window.document.querySelector('#flow details').open, '#flow 直リンクは会議の詳細を開く');
assert.ok(!live.window.document.querySelector('#board details').open, '無関係な詳細は閉じたまま');
console.log('PASS 旧アンカーの互換性');
live.window.location.hash = '#deliverables';
await new Promise(resolve => setTimeout(resolve,40));
assert.ok(!live.window.document.querySelector('.artifact-archive').open, '成果物へ移動しても技術詳細は閉じたまま');
console.log('PASS 成果物アンカーは一覧を勝手に展開しない');
live.window.location.hash = '#board';
await new Promise(resolve => setTimeout(resolve,40));
assert.ok(live.window.document.querySelector('#board details').open, '#board で担当タスクを展開する');
console.log('PASS タスクへの直リンク');
const baseline = JSON.parse(readFileSync('scripts/fixtures/pros-dashboard-baseline.json', 'utf8'));
const hrefs = [...d.querySelectorAll('a')].map(a => a.getAttribute('href'));
for (const href of baseline.links) assert.ok(hrefs.includes(href), `元のリンク維持: ${href}`);
const taskIds = [...live.window.document.querySelectorAll('input[data-id]')].map(i=>i.dataset.id);
assert.deepEqual(taskIds.sort(), baseline.taskIds.sort(), '全タスクIDを維持');
assert.equal(d.querySelectorAll('.artifact-archive a').length, 12);
assert.equal(d.querySelector('video').hasAttribute('autoplay'), false);
assert.equal(d.querySelectorAll('h1').length, 1);
const ids = [...d.querySelectorAll('[id]')].map(el=>el.id);
assert.equal(new Set(ids).size, ids.length, '重複IDなし');
console.log('PASS 全12成果物・全44タスク・既存リンクを維持');
live.window.close(); dom.window.close();
